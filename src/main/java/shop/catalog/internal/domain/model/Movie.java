package shop.catalog.internal.domain.model;

import java.math.BigDecimal;

public class Movie {

    private Long id;

    private String title;

    private Integer year;

    private String genre;

    private String director;

    /** Average of the scores; {@code null} while there are no ratings. */
    private Double averageRating;

    /** Sale price; {@code null} only for movies that predate this field, which are not purchasable. */
    private BigDecimal price;

    /** Units available for orders; never negative. */
    private int stock;

    public int getStock() {
        return stock;
    }

    public void setStock(int stock) {
        this.stock = stock;
    }

    public BigDecimal getPrice() {
        return price;
    }

    public void setPrice(BigDecimal price) {
        this.price = price;
    }

    public Long getId() {
        return id;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public String getTitle() {
        return title;
    }

    public void setTitle(String title) {
        this.title = title;
    }

    public Integer getYear() {
        return year;
    }

    public void setYear(Integer year) {
        this.year = year;
    }

    public String getGenre() {
        return genre;
    }

    public void setGenre(String genre) {
        this.genre = genre;
    }

    public String getDirector() {
        return director;
    }

    public void setDirector(String director) {
        this.director = director;
    }

    public Double getAverageRating() {
        return averageRating;
    }

    public void setAverageRating(Double averageRating) {
        this.averageRating = averageRating;
    }
}
